class Solution:
    def twoSum(self, nums, target):
        left = 0
        right = len(nums) - 1

        while left < right:
            total = nums[left] + nums[right]

            if total == target:
                return [left, right]

            elif total > target:
                right -= 1

            else:
                left += 1

        return []

